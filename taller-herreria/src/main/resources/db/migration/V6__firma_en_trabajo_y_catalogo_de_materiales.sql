-- Dos cosas independientes en la misma versión: la firma del cliente pasa a
-- poder recogerse en el trabajo, y los materiales dejan de teclearse para
-- elegirse de un catálogo que mantiene el jefe, agrupado por familias.

-- ---------------------------------------------------------------------------
-- 1. Firma en el trabajo
--
-- La recoge el trabajador en la obra, desde la tablet, sin esperar a que el
-- jefe genere el albarán. Un albarán de UN solo trabajo la hereda; uno
-- unificado no, porque el cliente firmó cada visita, no el documento del mes.
-- bytea y no oid, por lo mismo que la firma del albarán y las fotos: un large
-- object no se libera al borrar la fila.
-- ---------------------------------------------------------------------------

ALTER TABLE trabajos ADD COLUMN firma                bytea;
ALTER TABLE trabajos ADD COLUMN firma_tipo_contenido varchar(255);

-- ---------------------------------------------------------------------------
-- 2. Catálogo de materiales, agrupado por familias
-- ---------------------------------------------------------------------------

CREATE TABLE familias_material (
    id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255) NOT NULL,
    CONSTRAINT uq_familia_material_nombre UNIQUE (nombre)
);

CREATE TABLE catalogo_materiales (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    familia_id       bigint         NOT NULL,
    nombre           varchar(255)   NOT NULL,
    -- m, ud, kg, barra… La pone el jefe una vez; sin ella un precio no dice
    -- si es por metro o por barra.
    unidad           varchar(20)    NOT NULL DEFAULT 'ud',
    -- Nulo mientras no se sepa: entonces la línea llega al albarán sin precio
    -- y el jefe lo pone a mano.
    precio           numeric(10, 2),
    porcentaje_extra numeric(6, 2)  NOT NULL DEFAULT 0,
    transporte       numeric(10, 2) NOT NULL DEFAULT 0,

    -- Sin cascada: una familia con materiales dentro no se borra. El servicio
    -- lo corta antes con un 409 diciendo cuántos tiene.
    CONSTRAINT fk_catalogo_familia FOREIGN KEY (familia_id)
        REFERENCES familias_material (id),
    CONSTRAINT ck_catalogo_precio_positivo     CHECK (precio IS NULL OR precio >= 0),
    CONSTRAINT ck_catalogo_extra_positivo      CHECK (porcentaje_extra >= 0),
    CONSTRAINT ck_catalogo_transporte_positivo CHECK (transporte >= 0)
);

-- El mismo nombre no se repite dentro de una familia, sin distinguir
-- mayúsculas: es justo el desorden que el catálogo viene a quitar.
CREATE UNIQUE INDEX uq_catalogo_familia_nombre
    ON catalogo_materiales (familia_id, lower(nombre));

-- ---------------------------------------------------------------------------
-- 3. Las líneas de material de trabajos y albaranes enlazan con el catálogo
--
-- El enlace es para saber de qué material salió, no para leer de él: nombre,
-- unidad y precio se COPIAN a la línea. Si el mes que viene sube el hierro y
-- el jefe cambia el catálogo, un albarán ya entregado no puede cambiar su
-- total; se cobró a otro precio.
--
-- ON DELETE SET NULL por lo mismo: borrar un material del catálogo no rompe
-- ningún documento, que conserva su propia copia del nombre.
-- ---------------------------------------------------------------------------

ALTER TABLE materiales ADD COLUMN catalogo_id bigint;
ALTER TABLE materiales ADD COLUMN unidad      varchar(20);

ALTER TABLE materiales ADD CONSTRAINT fk_material_catalogo
    FOREIGN KEY (catalogo_id) REFERENCES catalogo_materiales (id) ON DELETE SET NULL;
