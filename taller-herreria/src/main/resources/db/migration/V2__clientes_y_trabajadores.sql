-- Clientes y trabajadores dejan de ser texto escrito a mano y pasan a ser
-- entidades que el jefe gestiona desde Ajustes.
--
-- El motivo es que el mismo cliente acababa escrito de tres formas distintas
-- ("Comunidad Los Alamos", "C. Los Álamos", "los alamos") y no había forma de
-- agrupar sus trabajos. Al ser una referencia y no una copia, corregir una
-- errata en Ajustes la corrige en todos los documentos a la vez.
--
-- OJO: esto cambia a propósito la regla de que el albarán es una copia
-- instantánea. Sigue siéndolo para el resto de campos; el cliente y el
-- trabajador pasan a ser referencias vivas. Decisión del dueño del proyecto.

-- ---------------------------------------------------------------------------
-- 1. Las dos tablas nuevas
-- ---------------------------------------------------------------------------

CREATE TABLE clientes (
    id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255) NOT NULL,
    CONSTRAINT uq_cliente_nombre UNIQUE (nombre)
);

CREATE TABLE trabajadores (
    id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(255) NOT NULL,
    CONSTRAINT uq_trabajador_nombre UNIQUE (nombre)
);

-- ---------------------------------------------------------------------------
-- 2. Sembrarlas con lo que ya hay escrito
--
-- Se recogen los nombres de las tres tablas, se limpian los espacios y se
-- quitan los duplicados. Si alguien escribió el mismo cliente con mayúsculas
-- distintas quedarán dos fichas: es preferible a fusionarlas a ciegas y
-- atribuirle a alguien un trabajo que no es suyo. El jefe las unifica a mano
-- desde Ajustes, que para eso puede editar y borrar.
-- ---------------------------------------------------------------------------

INSERT INTO clientes (nombre)
SELECT DISTINCT trim(cliente)
FROM (
    SELECT cliente FROM pedidos
    UNION ALL SELECT cliente FROM trabajos
    UNION ALL SELECT cliente FROM albaranes
) AS todos
WHERE cliente IS NOT NULL AND trim(cliente) <> '';

INSERT INTO trabajadores (nombre)
SELECT DISTINCT trim(trabajador)
FROM (
    SELECT trabajador FROM pedidos
    UNION ALL SELECT trabajador FROM trabajos
    UNION ALL SELECT trabajador FROM albaranes
) AS todos
WHERE trabajador IS NOT NULL AND trim(trabajador) <> '';

-- ---------------------------------------------------------------------------
-- 3. Pedidos: cliente y trabajador son obligatorios (el pedido nace completo)
-- ---------------------------------------------------------------------------

ALTER TABLE pedidos ADD COLUMN cliente_id    bigint;
ALTER TABLE pedidos ADD COLUMN trabajador_id bigint;

UPDATE pedidos p SET cliente_id    = c.id FROM clientes c      WHERE c.nombre = trim(p.cliente);
UPDATE pedidos p SET trabajador_id = t.id FROM trabajadores t  WHERE t.nombre = trim(p.trabajador);

ALTER TABLE pedidos ALTER COLUMN cliente_id    SET NOT NULL;
ALTER TABLE pedidos ALTER COLUMN trabajador_id SET NOT NULL;

ALTER TABLE pedidos ADD CONSTRAINT fk_pedido_cliente
    FOREIGN KEY (cliente_id) REFERENCES clientes (id);
ALTER TABLE pedidos ADD CONSTRAINT fk_pedido_trabajador
    FOREIGN KEY (trabajador_id) REFERENCES trabajadores (id);

ALTER TABLE pedidos DROP COLUMN cliente;
ALTER TABLE pedidos DROP COLUMN trabajador;

-- ---------------------------------------------------------------------------
-- 4. Trabajos: nullable, porque un borrador puede estar a medias
-- ---------------------------------------------------------------------------

ALTER TABLE trabajos ADD COLUMN cliente_id    bigint;
ALTER TABLE trabajos ADD COLUMN trabajador_id bigint;

UPDATE trabajos t2 SET cliente_id    = c.id FROM clientes c     WHERE c.nombre = trim(t2.cliente);
UPDATE trabajos t2 SET trabajador_id = t.id FROM trabajadores t WHERE t.nombre = trim(t2.trabajador);

ALTER TABLE trabajos ADD CONSTRAINT fk_trabajo_cliente
    FOREIGN KEY (cliente_id) REFERENCES clientes (id);
ALTER TABLE trabajos ADD CONSTRAINT fk_trabajo_trabajador
    FOREIGN KEY (trabajador_id) REFERENCES trabajadores (id);

ALTER TABLE trabajos DROP COLUMN cliente;
ALTER TABLE trabajos DROP COLUMN trabajador;

-- ---------------------------------------------------------------------------
-- 5. Albaranes: un cliente, pero VARIOS trabajadores
--
-- Lo segundo es nuevo: al unificar varios trabajos de un mismo cliente en un
-- solo albarán, intervienen varias personas. Por eso el trabajador deja de ser
-- una columna y pasa a ser una tabla de relación.
-- ---------------------------------------------------------------------------

ALTER TABLE albaranes ADD COLUMN cliente_id bigint;

UPDATE albaranes a SET cliente_id = c.id FROM clientes c WHERE c.nombre = trim(a.cliente);

ALTER TABLE albaranes ALTER COLUMN cliente_id SET NOT NULL;

ALTER TABLE albaranes ADD CONSTRAINT fk_albaran_cliente
    FOREIGN KEY (cliente_id) REFERENCES clientes (id);

CREATE TABLE albaran_trabajadores (
    albaran_id    bigint NOT NULL,
    trabajador_id bigint NOT NULL,
    PRIMARY KEY (albaran_id, trabajador_id),
    CONSTRAINT fk_at_albaran FOREIGN KEY (albaran_id)
        REFERENCES albaranes (id) ON DELETE CASCADE,
    CONSTRAINT fk_at_trabajador FOREIGN KEY (trabajador_id)
        REFERENCES trabajadores (id)
);

INSERT INTO albaran_trabajadores (albaran_id, trabajador_id)
SELECT a.id, t.id
FROM albaranes a
JOIN trabajadores t ON t.nombre = trim(a.trabajador);

ALTER TABLE albaranes DROP COLUMN cliente;
ALTER TABLE albaranes DROP COLUMN trabajador;
