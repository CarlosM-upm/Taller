-- Los materiales dejan de ser un texto libre y pasan a ser líneas con nombre y
-- cantidad.
--
-- El motivo es que hay que ponerles precio en el albarán y sumar cantidades al
-- unificar varios trabajos del mismo cliente. Con "2 m de perfil, 4 tornillos"
-- en una sola cadena no hay nada que multiplicar ni que sumar.
--
-- El albarán pasa además a guardar materiales y horas propios. Antes no los
-- tenía: eran datos internos del taller que se quedaban en el trabajo. Ahora
-- son la base del cálculo del coste, así que tienen que viajar.

CREATE TABLE materiales (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origen_tipo varchar(20)    NOT NULL,
    origen_id   bigint         NOT NULL,
    nombre      varchar(255)   NOT NULL,
    cantidad    numeric(10, 2) NOT NULL,
    -- Nulo salvo en albaranes: lo pone el jefe al facturar, y el trabajador
    -- que apunta el material desde la tablet no tiene por qué saber el precio.
    precio      numeric(10, 2),
    CONSTRAINT ck_material_origen_tipo CHECK (origen_tipo IN ('TRABAJO', 'ALBARAN'))
);

CREATE INDEX idx_material_origen ON materiales (origen_tipo, origen_id);

-- ---------------------------------------------------------------------------
-- Convertir el texto que ya hay
--
-- No se intenta trocear la cadena por comas: "2 m de perfil, 4 tornillos" y
-- "tubo 40x40, 2 uds" no siguen ninguna regla fiable, y partir mal un material
-- es peor que dejarlo entero. Cada trabajo con materiales se queda con UNA
-- línea que contiene el texto tal cual y cantidad 1, para que el jefe la separe
-- a mano cuando le convenga.
-- ---------------------------------------------------------------------------

INSERT INTO materiales (origen_tipo, origen_id, nombre, cantidad)
SELECT 'TRABAJO', id, left(trim(materiales), 255), 1
FROM trabajos
WHERE materiales IS NOT NULL AND trim(materiales) <> '';

ALTER TABLE trabajos DROP COLUMN materiales;

-- ---------------------------------------------------------------------------
-- El albarán gana horas propias, y hereda las del trabajo del que salió
-- ---------------------------------------------------------------------------

ALTER TABLE albaranes ADD COLUMN horas numeric(7, 2);

UPDATE albaranes a
SET horas = t.horas
FROM trabajos t
WHERE t.id = a.trabajo_id;

-- Y los materiales del trabajo se copian como materiales propios del albarán,
-- igual que ya se hacía con las fotos: el albarán es una instantánea.
INSERT INTO materiales (origen_tipo, origen_id, nombre, cantidad)
SELECT 'ALBARAN', a.id, m.nombre, m.cantidad
FROM albaranes a
JOIN materiales m ON m.origen_tipo = 'TRABAJO' AND m.origen_id = a.trabajo_id;
